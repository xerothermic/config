function M.clear()
  for i = #history, 1, -1 do removeAt(i) end
  save()
  hs.alert.show("clipboard history cleared", 0.8)
end

function M.show()
  if visible then hide(true) return end -- hotkey toggles
  capture() -- pick up anything copied since the last poll
  prevApp = hs.application.frontmostApplication()

  local f = (hs.mouse.getCurrentScreen() or hs.screen.mainScreen()):frame()
  web:frame({ x = f.x + (f.w - WIN_W) / 2, y = f.y + f.h * 0.15, w = WIN_W, h = WIN_H })
  if ready then js("App.open", buildPayload()) else pendingOpen = true end

  visible = true
  web:show()
  hs.focus()
  local win = web:hswindow()
  if win then win:focus() end
  web:evaluateJavaScript("window.App && App.focus()")
end

function M.start()
  load()
  createWebview()
  pollTimer = hs.timer.doEvery(POLL_INTERVAL, capture)
  M.timer = pollTimer -- keep a reference so it isn't garbage collected
  M.hotkey = hs.hotkey.bind({ "cmd", "alt" }, "c", M.show)
  return M
end

return M
