local web, prevApp
local visible, ready, pendingOpen = false, false, nil
local sent = {} -- asset keys (icons, thumbnails) the page already holds

local function thumb(item)
  local img = thumbCache[item.file]
  if not img then
    img = hs.image.imageFromPath(item.file)
    thumbCache[item.file] = img
  end
  return img
end

-- PNG data URL, scaled so the longer side is at most maxSide pixels
-- (icons report a small nominal size, so they may scale up to maxSide)
local function dataURL(img, maxSide, allowUpscale)
  if not img then return nil end
  local s = img:size()
  local k = maxSide / math.max(s.w, s.h, 1)
  if not allowUpscale then k = math.min(1, k) end
  return img:copy()
            :setSize({ w = math.max(1, math.floor(s.w * k)), h = math.max(1, math.floor(s.h * k)) }, true)
            :encodeAsURLString(true, "PNG")
end

local function js(fn, ...)
  local ok, args = pcall(hs.json.encode, { ... })
  if not ok or not args then return end
  web:evaluateJavaScript(fn .. ".apply(null, " .. args .. ")")
end

local function findIndex(id)
  for i, item in ipairs(history) do
    if item.hash == id then return i end
  end
end

-- trim a string to n bytes without leaving a broken UTF-8 tail
local function cut(s, n)
  if #s <= n then return s, false end
  return (s:sub(1, n):gsub("[\192-\255][\128-\191]*$", "")), true
end

local function buildPayload()
  local items, assets = {}, {}
  local function asset(key, make)
    if sent[key] then return end
    local url = make()
    if url then assets[key], sent[key] = url, true end
  end

  for _, it in ipairs(history) do
    local e = { id = it.hash, kind = it.kind, time = it.time, appName = it.appName }
    if it.kind == "text" then
      e.text, e.truncated = cut(it.text, 20000)
      e.chars = utf8.len(it.text) or #it.text
      e.lines = select(2, it.text:gsub("\n", "")) + 1
      e.app = it.app or "_text"
      asset("icon:" .. e.app, function()
        local img = it.app and hs.image.imageFromAppBundle(it.app)
                    or hs.image.iconForFileType("public.plain-text")
        return dataURL(img, 64, true)
      end)
    else
      e.w, e.h = it.w, it.h
      asset("thumb:" .. it.hash, function() return dataURL(thumb(it), 96) end)
    end
    -- skip anything that isn't valid UTF-8; it would break the JSON payload
    if e.kind == "image" or utf8.len(e.text) then items[#items + 1] = e end
  end
  return { items = items, assets = assets }
end

local function writeToPasteboard(item)
  if item.kind == "text" then
    hs.pasteboard.setContents(item.text)
  else
    local img = thumb(item)
    if not img then return false end
    hs.pasteboard.writeObjects(img)
  end
  return true
end

local function hide(restoreFocus)
  if not visible then return end
  visible = false
  web:hide()
  if restoreFocus and prevApp then prevApp:activate() end
end

local handlers = {
  ready = function()
    ready, sent = true, {}
