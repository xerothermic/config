// subsequence match, case-insensitive; rewards consecutive runs, word starts, early matches
function fuzzy(qs, text) {
  const ts = Array.from(text);
  let score = 0, qi = 0, run = 0, first = -1;
  const hits = [];
  for (let i = 0; i < ts.length && qi < qs.length; i++) {
    if (ts[i].toLowerCase() === qs[qi]) {
      if (first < 0) first = i;
      run++;
      score += 1 + run * 2;
      if (i === 0 || /[\s\p{P}]/u.test(ts[i - 1])) score += 8;
      hits.push(i);
      qi++;
    } else {
      run = 0;
    }
  }
  if (qi < qs.length) return null;
  return { score: score - first * 0.1 - ts.length * 0.001, hits };
}

function highlight(title, qs) {
  const m = qs.length && fuzzy(qs, title);
  if (!m) return esc(title);
  const hit = new Set(m.hits);
  return Array.from(title).map((c, i) => hit.has(i) ? `<b class="hit">${esc(c)}</b>` : esc(c)).join('');
}

