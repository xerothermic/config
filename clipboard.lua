-- Clipboard history (text + images) with fuzzy search
--   cmd+opt+c                 open / close history
--   enter / click             copy + paste into the previous app
--   shift+enter               copy only (no paste)
--   cmd+delete / fn+delete    delete the highlighted entry (or right-click)
--   cmd+1…9                   pick a row directly
--   cmd+e / double-click      edit a text entry (cmd+enter or cmd+s saves, esc cancels)
--   esc / click outside       close
--   type ":clear"             shows a confirm row; enter on it wipes history
--------------------------------------------------------------------
local M = {}

local MAX_ITEMS     = 300
local POLL_INTERVAL = 0.5 -- seconds
local DATA_DIR      = hs.configdir .. "/clipboard_history"
local DB_FILE       = DATA_DIR .. "/history.json"

-- pasteboard types set by password managers etc. (nspasteboard.org)
local IGNORED_TYPES = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
  ["com.agilebits.onepassword"] = true,
}

local history = {}    -- newest first: { kind="text"|"image", text|file, hash, time, w, h }
local thumbCache = {} -- file -> hs.image
local lastChange = hs.pasteboard.changeCount()
local pollTimer

--------------------------------------------------------------------
-- persistence
--------------------------------------------------------------------
hs.fs.mkdir(DATA_DIR)

local function save()
  hs.json.write(history, DB_FILE, false, true)
end

local function load()
  local data = hs.json.read(DB_FILE)
  if type(data) ~= "table" then return end
  for _, item in ipairs(data) do
    -- drop images whose file has gone missing
    if item.kind == "text" or (item.kind == "image" and hs.fs.attributes(item.file)) then
      table.insert(history, item)
    end
  end
end

local function removeAt(i)
  local item = table.remove(history, i)
  if item and item.kind == "image" then
    thumbCache[item.file] = nil
    os.remove(item.file)
  end
end

local function trim()
  while #history > MAX_ITEMS do removeAt(#history) end
end

--------------------------------------------------------------------
-- capture
--------------------------------------------------------------------
local function push(item)
  -- duplicate → move it to the top instead of storing twice
  for i, old in ipairs(history) do
    if old.hash == item.hash then
      if i == 1 then return end
      table.insert(history, 1, table.remove(history, i))
      history[1].time = item.time
      save()
      return false
    end
  end
  table.insert(history, 1, item)
  trim()
  save()
  return true
end

local function shouldIgnore()
  for _, t in ipairs(hs.pasteboard.pasteboardTypes() or {}) do
    if IGNORED_TYPES[t] then return true end
  end
  return false
end

local function capture()
  local count = hs.pasteboard.changeCount()
  if count == lastChange then return end
  lastChange = count
  if shouldIgnore() then return end

  local now = os.time()
  -- remember where it came from so the list can show the app's icon
  local app = hs.application.frontmostApplication()
  local src = { app = app and app:bundleID(), appName = app and app:name() }
  local function tag(item)
    item.app, item.appName = src.app, src.appName
    return item
  end

  -- prefer text: copying from many apps also puts an image rendition on the board
  local text = hs.pasteboard.readString()
  if text and text:match("%S") then
    push(tag({ kind = "text", text = text, hash = hs.hash.MD5(text), time = now }))
    return
  end

  local img = hs.pasteboard.readImage()
  if img then
    local png = img:encodeAsURLString(false, "PNG")
    if not png then return end
    local hash = hs.hash.MD5(png)
    local size = img:size()
    local file = string.format("%s/%s.png", DATA_DIR, hash)
    local item = { kind = "image", file = file, hash = hash, time = now,
                   w = math.floor(size.w), h = math.floor(size.h) }
    if push(tag(item)) then
      img:saveToFile(file)
      thumbCache[file] = img
    end
  end
end

