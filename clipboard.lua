  end,
  clear = function()
    hide(true)
    M.clear()
  end,
  preview = function(msg)
    local i = findIndex(msg.id)
    if i then js("App.preview", msg.id, dataURL(thumb(history[i]), 1400)) end
  end,
}

local function onMessage(msg)
  local body = msg.body
  local fn = type(body) == "table" and handlers[body.type]
  if fn then fn(body) end
end

local function createWebview()
  local uc = hs.webview.usercontent.new("clip"):setCallback(onMessage)
  web = hs.webview.new({ x = 0, y = 0, w = WIN_W, h = WIN_H }, {}, uc)
    :windowStyle({ "borderless" })
    :transparent(true)
    :shadow(false) -- the panel draws its own CSS shadow
    :allowTextEntry(true)
    :closeOnEscape(false)
    :deleteOnClose(false)
    :level(hs.drawing.windowLevels.modalPanel)
    :behaviorAsLabels({ "moveToActiveSpace", "fullScreenAuxiliary" })
    :windowCallback(function(action, _, focused)
      -- clicked into another app: just get out of the way
      if action == "focusChange" and not focused then hide(false) end
    end)
    :html(HTML)
end

