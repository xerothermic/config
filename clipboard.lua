  paste = function(msg)
    local i = findIndex(msg.id)
    if not i or not writeToPasteboard(history[i]) then return end
    hide(true)
    if not msg.copyOnly then
      -- give focus a moment to land back in the previous app
      hs.timer.doAfter(0.15, function() hs.eventtap.keyStroke({ "cmd" }, "v", 0) end)
    end
  end,
  edit = function(msg)
    local i = findIndex(msg.id)
    if not i or type(msg.text) ~= "string" or not msg.text:match("%S") then return end
